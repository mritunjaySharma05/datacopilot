"""Evaluate answerability classifiers on the 30-question human held-out set.

Models:
  main            the saved, deployed model (models/answerability.joblib; no n_words since 2026-11-18)
  logreg          logistic regression, C chosen by grouped 5-fold CV on train rows
  logreg_no_nwords  the same procedure without n_words (only that one feature differs)

The two logreg models make a fair n_words ablation: same model family, C grid, folds and
training rows. Each model is scored on the test split (180) and on the held-out set (30).
Held-out rows are never used for fitting or choosing anything.

Writes docs/results/heldout.md and docs/results/heldout_metrics.json.

Usage:
    python scripts/eval_heldout.py
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from build_features import build_feature_table, dataset_inputs  # noqa: E402
from datacopilot.pipeline.answerability import (  # noqa: E402
    MODEL_PATH, PARAM_GRIDS, cv_groups, evaluate, fit_best, load_model, search,
)
from datacopilot.pipeline.features import FEATURE_NAMES  # noqa: E402
from datacopilot.questions import PROCESSED_DIR, QUESTIONS_DIR, load_heldout  # noqa: E402

FEATURES_PATH = ROOT / "data" / "features" / "answerability_features.csv"
RESULTS_DIR = ROOT / "docs" / "results"
LOGREG_GRID = {"logreg": PARAM_GRIDS["logreg"]}


def heldout_table(rows: list[dict], inputs: dict) -> pd.DataFrame:
    """Feature table for held-out rows; question_set is "heldout_<language>" for per-language scores."""
    table = build_feature_table([{**r, "question_set": f"heldout_{r['language']}"} for r in rows], inputs)
    table["question"] = [r["question"] for r in rows]
    return table


def fit_logreg(train: pd.DataFrame, features: list[str], grid: dict | None = None, n_folds: int = 5) -> dict:
    """Logistic regression with C chosen by grouped CV on train rows; returns a model bundle."""
    best = search(train[features], train.answerable, cv_groups(train.id), grid or LOGREG_GRID, n_folds)[0]
    return {"model": fit_best(train[features], train.answerable, best), "feature_names": features,
            "params": best.params, "cv_macro_f1": round(best.mean, 4)}


def score(bundle: dict, table: pd.DataFrame) -> tuple[dict, pd.DataFrame]:
    """Metrics plus the misclassified rows (id, question, label, P(answerable))."""
    X = table[bundle["feature_names"]]
    prob = bundle["model"].predict_proba(X)[:, 1]
    pred = (prob >= bundle.get("threshold", 0.5)).astype(int)
    metrics = evaluate(table.answerable, pred, table)
    cols = [c for c in ("id", "question", "dataset", "answerable", "unanswerable_type") if c in table]
    mask = pred != table.answerable.to_numpy()
    wrong = table.loc[mask, cols].assign(p_answerable=prob[mask])
    return metrics, wrong.reset_index(drop=True)


def run(train: pd.DataFrame, test: pd.DataFrame, heldout: pd.DataFrame, main_bundle: dict,
        grid: dict | None = None, n_folds: int = 5) -> dict:
    """Score main, logreg and logreg_no_nwords on test and held-out rows."""
    bundles = {
        "main": main_bundle,
        "logreg": fit_logreg(train, list(FEATURE_NAMES), grid, n_folds),
        "logreg_no_nwords": fit_logreg(train, [f for f in FEATURE_NAMES if f != "n_words"], grid, n_folds),
    }
    results = {}
    for name, bundle in bundles.items():
        test_m, _ = score(bundle, test)
        held_m, wrong = score(bundle, heldout)
        results[name] = {"params": bundle.get("params"), "cv_macro_f1": bundle.get("cv_macro_f1"),
                         "test": test_m, "heldout": held_m, "misclassified": wrong}
    return results


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def report(results: dict, n_heldout: int) -> str:
    """Markdown report."""
    lines = [
        "# Answerability classifier: human held-out set",
        "",
        f"Generated by `scripts/eval_heldout.py`. Held-out set: {n_heldout} questions in",
        "`data/questions/human_heldout.jsonl` (AI-drafted, human-edited; never used for training or",
        "model choice). Unanswerable is the positive class for precision / recall.",
        "",
        "- **main**: the deployed model (`models/answerability.joblib`, without `n_words`).",
        "- **logreg** vs **logreg_no_nwords**: fair `n_words` ablation. Both are logistic regression",
        "  with C chosen by the same grouped 5-fold CV on the same 420 train rows; only `n_words` differs.",
        "",
        "| Model | Params (by CV) | Set | Accuracy | Macro F1 | Unans. precision | Unans. recall | Errors |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, r in results.items():
        c = ", ".join(f"{k.removeprefix('clf__')}={v}" for k, v in (r["params"] or {}).items()) or "-"
        for split in ("test", "heldout"):
            m = r[split]
            errors = m["confusion_matrix"][0][1] + m["confusion_matrix"][1][0]
            lines.append(f"| {name} | {c} | {split} ({m['n']}) | {pct(m['accuracy'])} | {m['macro_f1']:.3f} | "
                         f"{pct(m['unanswerable_precision'])} | {pct(m['unanswerable_recall'])} | {errors} |")
    names = list(results)
    for key, title in [("accuracy_by_question_set", "Held-out accuracy by language"),
                       ("recall_by_unanswerable_type", "Held-out recall per unanswerable type (3 questions each)"),
                       ("accuracy_by_dataset", "Held-out accuracy per dataset")]:
        lines += ["", f"## {title}", "", "| | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
        for k in results["main"]["heldout"][key]:
            lines.append(f"| {k} | " + " | ".join(pct(results[n]["heldout"][key].get(k, float("nan")))
                                                  for n in names) + " |")
    lines += ["", "## Misclassified held-out questions", ""]
    for name, r in results.items():
        wrong = r["misclassified"]
        lines += [f"### {name} ({len(wrong)} wrong)", ""]
        if wrong.empty:
            lines += ["None.", ""]
            continue
        lines += ["| Id | Question | True label | Type | P(answerable) |", "|---|---|---|---|---|"]
        for w in wrong.itertuples():
            label = "answerable" if w.answerable else "unanswerable"
            utype = w.unanswerable_type if isinstance(w.unanswerable_type, str) else ""
            lines.append(f"| {w.id} | {w.question} | {label} | {utype} | {w.p_answerable:.2f} |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description="Evaluate answerability models on the human held-out set.")
    parser.add_argument("--features", type=Path, default=FEATURES_PATH)
    parser.add_argument("--questions-dir", type=Path, default=QUESTIONS_DIR)
    parser.add_argument("--processed-dir", type=Path, default=PROCESSED_DIR)
    parser.add_argument("--model", type=Path, default=MODEL_PATH)
    parser.add_argument("--results-dir", type=Path, default=RESULTS_DIR)
    args = parser.parse_args(argv)

    table = pd.read_csv(args.features)
    rows = load_heldout(args.questions_dir)
    inputs = {ds: dataset_inputs(ds, args.processed_dir) for ds in sorted({r["dataset"] for r in rows})}
    held = heldout_table(rows, inputs)
    results = run(table[table.split == "train"], table[table.split == "test"], held, load_model(args.model))
    for name, r in results.items():
        print(f"{name:17} test acc {r['test']['accuracy']:.3f} | heldout acc {r['heldout']['accuracy']:.3f} "
              f"({len(r['misclassified'])} wrong)")
    args.results_dir.mkdir(parents=True, exist_ok=True)
    (args.results_dir / "heldout.md").write_text(report(results, len(held)), encoding="utf-8")
    metrics = {n: {**{k: v for k, v in r.items() if k != "misclassified"},
                   "misclassified": r["misclassified"].round(4).to_dict(orient="records")}
               for n, r in results.items()}
    (args.results_dir / "heldout_metrics.json").write_text(json.dumps(metrics, indent=2, default=str) + "\n",
                                                           encoding="utf-8")
    print(f"Report: {args.results_dir / 'heldout.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
