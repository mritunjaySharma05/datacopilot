"""Compare two LLM providers on the same questions (Module 5 validation: Groq vs the Module 4 Ollama run).

Pairs two validated-mode runs of scripts/eval_questions.py by question id and reports strict
and relaxed accuracy by dataset and language, outcome counts, latency, every question where the
providers differ on the strict metric, and an exact McNemar test on the paired results.

Defaults (data/results/):
  reference  newest questions_validated_csv+hinglish_test_*_rescored.csv   (Module 4, Ollama;
             rescored with the current relaxed rules, strict unchanged)
  candidate  newest questions_validated-groq_csv+hinglish_test_*.csv       (Module 5, Groq)

Usage:
    python scripts/compare_providers.py
    python scripts/compare_providers.py --runs OLLAMA.csv GROQ.csv
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from compare_modes import accuracy_by, mcnemar_exact, pair_runs  # noqa: E402

RESULTS_DIR = ROOT / "data" / "results"
REPORT = ROOT / "docs" / "results" / "groq_vs_ollama.md"
LABEL = "csv+hinglish_test"
METRICS = ("strict", "relaxed")
STATUSES = ("correct", "wrong_result", "validation_failed", "execution_failed")


def newest(results_dir: Path, pattern: str) -> Path:
    paths = sorted(results_dir.glob(pattern))
    if not paths:
        raise FileNotFoundError(f"No {pattern} in {results_dir}")
    return paths[-1]


def pair(reference: pd.DataFrame, candidate: pd.DataFrame) -> pd.DataFrame:
    """One row per question: _c = candidate (e.g. Groq), _r = reference (e.g. Ollama), plus language."""
    p = pair_runs(candidate, reference)
    p = p.rename(columns=lambda c: c[:-2] + "_c" if c.endswith("_v") else (c[:-2] + "_r" if c.endswith("_b") else c))
    seconds = candidate.set_index("id").seconds.rename("seconds_c").to_frame().join(
        reference.set_index("id").seconds.rename("seconds_r"))
    return p.merge(seconds, left_on="id", right_index=True, how="left")


def by_group(paired: pd.DataFrame, by: str) -> pd.DataFrame:
    """n and accuracy per group for both providers and metrics, plus 'all'."""
    renamed = paired.rename(columns={f"{m}_{s}": f"{m}_{t}" for m in METRICS for s, t in (("c", "v"), ("r", "b"))})
    t = accuracy_by(renamed, by)
    return t.rename(columns={f"{m}_{t_}": f"{m}_{s}" for m in METRICS for s, t_ in (("c", "v"), ("r", "b"))})


def mcnemar(paired: pd.DataFrame, metric: str) -> dict:
    t = mcnemar_exact(paired[f"{metric}_c"], paired[f"{metric}_r"])
    return {"only_candidate": t["only_validated"], "only_reference": t["only_baseline"],
            "discordant": t["discordant"], "p_value": t["p_value"]}


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def report(paired: pd.DataFrame, ref_name: str, cand_name: str, ref_file: str, cand_file: str) -> str:
    """Markdown report."""
    lines = [f"# {cand_name} vs {ref_name}: same 90 test questions, validated mode", "",
             f"Generated by `scripts/compare_providers.py`. Reference: `{ref_file}` (Module 4 step 3).",
             f"Candidate: `{cand_file}` (Module 5). Same prompt, temperature 0, validator and one retry;",
             "only the LLM differs. Strict (primary) = same rows and values as the gold answer. Relaxed",
             "(secondary; rules fixed after seeing the first Module 4 step 3 results) = every gold column, or",
             "exactly the key columns; row order only for top-N questions. McNemar's test (exact, two-sided)",
             "uses only the questions where exactly one provider is right.", ""]
    s, r = mcnemar(paired, "strict"), mcnemar(paired, "relaxed")
    lines += [f"**Strict: {cand_name} {_pct(paired.strict_c.mean())} vs {ref_name} {_pct(paired.strict_r.mean())}** "
              f"({int(paired.strict_c.sum())} vs {int(paired.strict_r.sum())} of {len(paired)}); "
              f"{cand_name} only right {s['only_candidate']}, {ref_name} only right {s['only_reference']}, "
              f"p = {s['p_value']:.4f}.", "",
              f"**Relaxed: {cand_name} {_pct(paired.relaxed_c.mean())} vs {ref_name} {_pct(paired.relaxed_r.mean())}**; "
              f"{cand_name} only right {r['only_candidate']}, {ref_name} only right {r['only_reference']}, "
              f"p = {r['p_value']:.4f}.", ""]
    for by in ("dataset", "language"):
        t = by_group(paired, by)
        lines += [f"## Accuracy by {by}", "",
                  f"| {by} | n | {ref_name} strict | {cand_name} strict | {ref_name} relaxed | {cand_name} relaxed |",
                  "|---|---|---|---|---|---|"]
        for grp, row in t.iterrows():
            name = f"**{grp}**" if grp == "all" else grp
            lines.append(f"| {name} | {int(row.n)} | {_pct(row.strict_r)} | {_pct(row.strict_c)} | "
                         f"{_pct(row.relaxed_r)} | {_pct(row.relaxed_c)} |")
        lines.append("")
    lines += ["## McNemar's test (exact, two-sided)", "",
              f"| Metric | {cand_name} only right | {ref_name} only right | discordant | p-value |",
              "|---|---|---|---|---|"]
    for m in METRICS:
        t = mcnemar(paired, m)
        lines.append(f"| {m} | {t['only_candidate']} | {t['only_reference']} | {t['discordant']} | {t['p_value']:.4f} |")
    counts = pd.DataFrame({ref_name: paired.status_r.value_counts(), cand_name: paired.status_c.value_counts()})
    counts = counts.reindex([x for x in STATUSES if x in counts.index] +
                            [x for x in counts.index if x not in STATUSES]).fillna(0).astype(int)
    lines += ["", "## Outcomes", "", f"| outcome | {ref_name} | {cand_name} |", "|---|---|---|"]
    lines += [f"| {o} | {row[ref_name]} | {row[cand_name]} |" for o, row in counts.iterrows()]
    if paired.seconds_c.notna().all() and paired.seconds_r.notna().all():
        lines += ["", "## Time per question (seconds, includes the retry; candidate includes rate-limit waits)", "",
                  f"| | {ref_name} | {cand_name} |", "|---|---|---|",
                  f"| median | {paired.seconds_r.median():.1f} | {paired.seconds_c.median():.1f} |",
                  f"| total | {paired.seconds_r.sum():.0f} | {paired.seconds_c.sum():.0f} |"]
    d = paired[paired.strict_c != paired.strict_r].sort_values("id")
    lines += ["", f"## Questions where the providers differ on strict ({len(d)})", ""]
    if d.empty:
        lines.append("None.")
    else:
        lines += [f"| id | question | right in | {ref_name} outcome | {cand_name} outcome |", "|---|---|---|---|---|"]
        for row in d.itertuples():
            q = row.question.replace("|", "\\|")
            lines.append(f"| {row.id} | {q} | {cand_name if row.strict_c else ref_name} | {row.status_r} | "
                         f"{row.status_c} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description="Compare two LLM providers on the same questions.")
    parser.add_argument("--runs", nargs=2, type=Path, metavar=("REFERENCE", "CANDIDATE"))
    parser.add_argument("--names", nargs=2, default=["Ollama qwen2.5-coder:7b", "Groq gpt-oss-120b"])
    parser.add_argument("--results-dir", type=Path, default=RESULTS_DIR)
    parser.add_argument("--out", type=Path, default=REPORT)
    args = parser.parse_args(argv)
    ref_path, cand_path = args.runs or (newest(args.results_dir, f"questions_validated_{LABEL}_*_rescored.csv"),
                                        newest(args.results_dir, f"questions_validated-groq_{LABEL}_*.csv"))
    paired = pair(pd.read_csv(ref_path), pd.read_csv(cand_path))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report(paired, *args.names, ref_path.name, cand_path.name), encoding="utf-8")
    print(f"{ref_path.name} vs {cand_path.name}\nReport: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
