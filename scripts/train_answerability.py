"""Train and evaluate the answerability classifier (Module 4).

Reads data/features/answerability_features.csv. For each experiment:
  1. grouped, stratified 5-fold CV on train rows only picks the model and hyperparameters
     (logistic regression, random forest, XGBoost; score = macro F1);
  2. the chosen configuration is refit on all train rows;
  3. it is scored once on the test rows.

Experiments:
  main          DEPLOYED_FEATURES (all but n_words), all train rows   -> saved to models/
  with_n_words  ablation: adds n_words back (a writing-style shortcut; dropped 2026-11-18)
  english_only  ablation: main features, trained on English rows only, tested on all test rows

Writes docs/results/answerability.md (report) and docs/results/answerability_metrics.json.

Usage:
    python scripts/train_answerability.py
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from datacopilot.pipeline.answerability import (  # noqa: E402
    EXCLUDED_FEATURES, MODEL_PATH, PARAM_GRIDS, cv_groups, evaluate, feature_weights, fit_best, save_model, search,
)
from datacopilot.pipeline.features import FEATURE_NAMES  # noqa: E402

FEATURES_PATH = ROOT / "data" / "features" / "answerability_features.csv"
RESULTS_DIR = ROOT / "docs" / "results"
ENGLISH_SETS = ("csv", "unanswerable")

EXPERIMENTS = {
    "main": {"drop": list(EXCLUDED_FEATURES), "train_sets": None},
    "with_n_words": {"drop": [], "train_sets": None},
    "english_only": {"drop": list(EXCLUDED_FEATURES), "train_sets": ENGLISH_SETS},
}


def run_experiment(table: pd.DataFrame, drop: list[str], train_sets: tuple[str, ...] | None,
                   grids: dict | None = None, n_folds: int = 5) -> dict:
    """Select by CV on train rows, refit, score once on all test rows."""
    features = [f for f in FEATURE_NAMES if f not in drop]
    train = table[table.split == "train"]
    if train_sets is not None:
        train = train[train.question_set.isin(train_sets)]
    test = table[table.split == "test"]
    results = search(train[features], train.answerable, cv_groups(train.id), grids, n_folds)
    best = results[0]
    model = fit_best(train[features], train.answerable, best)
    test_pred = model.predict(test[features])
    per_family = {}
    for r in results:  # best configuration of each model family (results are sorted best first)
        if r.model not in per_family:
            fam = fit_best(train[features], train.answerable, r)
            per_family[r.model] = {"params": r.params, "cv_macro_f1": round(r.mean, 4), "cv_std": round(r.std, 4),
                                   "test_macro_f1": round(evaluate(test.answerable, fam.predict(test[features]),
                                                                   test)["macro_f1"], 4)}
    return {
        "features": features,
        "n_train": int(len(train)),
        "best": {"model": best.model, "params": best.params, "cv_macro_f1": round(best.mean, 4),
                 "cv_std": round(best.std, 4)},
        "per_family": per_family,
        "test": evaluate(test.answerable, test_pred, test),
        "weights": feature_weights(model, features).round(4).to_dict(),
        "model": model,
    }


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def report(results: dict[str, dict]) -> str:
    """Markdown report of all experiments."""
    main = results["main"]
    t = main["test"]
    cm = t["confusion_matrix"]
    lines = [
        "# Answerability classifier: results",
        "",
        "Generated by `scripts/train_answerability.py`. Selection by grouped, stratified 5-fold CV",
        "(macro F1) on train rows only; each experiment is scored once on the test split",
        f"({t['n']} questions). Unanswerable is the positive class for precision / recall.",
        "",
        "## Experiments (test split)",
        "",
        "| Experiment | Train rows | Chosen model | CV macro F1 | Test accuracy | Test macro F1 | Unans. precision | Unans. recall |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, r in results.items():
        rt = r["test"]
        lines.append(f"| {name} | {r['n_train']} | {r['best']['model']} {r['best']['params']} | "
                     f"{r['best']['cv_macro_f1']:.3f} ± {r['best']['cv_std']:.3f} | {pct(rt['accuracy'])} | "
                     f"{rt['macro_f1']:.3f} | {pct(rt['unanswerable_precision'])} | {pct(rt['unanswerable_recall'])} |")
    lines += ["", "## Model families (main experiment)", "",
              "Best configuration of each family by CV. Test scores are shown for reference only;",
              "they were not used to choose the model.", "",
              "| Model | Params | CV macro F1 | Test macro F1 |", "|---|---|---|---|"]
    for fam, r in main["per_family"].items():
        lines.append(f"| {fam} | {r['params']} | {r['cv_macro_f1']:.3f} ± {r['cv_std']:.3f} | {r['test_macro_f1']:.3f} |")
    lines += ["", "## Main model: confusion matrix (test)", "",
              "| | predicted unanswerable | predicted answerable |", "|---|---|---|",
              f"| **unanswerable** | {cm[0][0]} | {cm[0][1]} |",
              f"| **answerable** | {cm[1][0]} | {cm[1][1]} |", ""]
    for key, title in [("recall_by_unanswerable_type", "Recall per unanswerable type (test)"),
                       ("accuracy_by_question_set", "Accuracy per question set (test)"),
                       ("accuracy_by_dataset", "Accuracy per dataset (test)")]:
        names = list(results)
        lines += [f"## {title}", "", "| | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
        for k in main["test"][key]:
            lines.append(f"| {k} | " + " | ".join(pct(results[n]["test"][key].get(k, float("nan"))) for n in names) + " |")
        lines.append("")
    lines += ["## Main model: top 10 feature weights", "",
              "Logistic regression: coefficient on standardized features (positive = answerable).",
              "Trees: impurity importance.", "", "| Feature | Weight |", "|---|---|"]
    lines += [f"| {f} | {w:.4f} |" for f, w in list(main["weights"].items())[:10]]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description="Train the answerability classifier.")
    parser.add_argument("--features", type=Path, default=FEATURES_PATH)
    parser.add_argument("--results-dir", type=Path, default=RESULTS_DIR)
    parser.add_argument("--model-out", type=Path, default=MODEL_PATH)
    args = parser.parse_args(argv)
    return train(args.features, args.results_dir, args.model_out)


def train(features_path: Path, results_dir: Path, model_out: Path, grids: dict | None = None,
          n_folds: int = 5) -> int:
    """Run all experiments, save the main model and write the report."""
    table = pd.read_csv(features_path)
    results = {}
    for name, cfg in EXPERIMENTS.items():
        results[name] = run_experiment(table, cfg["drop"], cfg["train_sets"], grids or PARAM_GRIDS, n_folds)
        r = results[name]
        print(f"{name:13} {r['best']['model']:13} CV {r['best']['cv_macro_f1']:.3f} | "
              f"test acc {r['test']['accuracy']:.3f} macro F1 {r['test']['macro_f1']:.3f}")
    main_r = results["main"]
    save_model(main_r["model"], main_r["features"],
               {"name": main_r["best"]["model"], "params": main_r["best"]["params"],
                "cv_macro_f1": main_r["best"]["cv_macro_f1"], "n_train": main_r["n_train"]}, model_out)
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "answerability.md").write_text(report(results), encoding="utf-8")
    metrics = {n: {k: v for k, v in r.items() if k != "model"} for n, r in results.items()}
    (results_dir / "answerability_metrics.json").write_text(json.dumps(metrics, indent=2, default=str) + "\n",
                                                             encoding="utf-8")
    print(f"Saved model to {model_out}; report in {results_dir / 'answerability.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
