"""Compare validated vs baseline BIRD runs of scripts/eval_bird.py on the same questions.

Reports BIRD execution accuracy (standard rule, unchanged: same set of rows) for both modes
by database and difficulty, failure categories, every question where the modes disagree,
and an exact McNemar test on the paired results.

Usage (defaults: newest bird_<mode>_sample300_seed42_*.csv in data/results/):
    python scripts/compare_bird.py
    python scripts/compare_bird.py --runs VALIDATED.csv BASELINE.csv
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from compare_modes import mcnemar_exact  # noqa: E402

RESULTS_DIR = ROOT / "data" / "results"
REPORT = ROOT / "docs" / "results" / "bird.md"
DEFAULT_TAG = "sample300_seed42"
DIFFICULTY_ORDER = ["simple", "moderate", "challenging"]


def outcome(row) -> str:
    """correct / wrong_result / validation_failed / execution_failed / gold_failed."""
    if row.correct:
        return "correct"
    error = row.error if isinstance(row.error, str) else ""
    if error.startswith("Gold SQL failed"):
        return "gold_failed"
    if error.startswith("Validation failed"):
        return "validation_failed"
    if error.startswith("Execution failed"):
        return "execution_failed"
    return "wrong_result"


def pair_runs(validated: pd.DataFrame, baseline: pd.DataFrame) -> pd.DataFrame:
    """One row per question with correct_v / correct_b and outcome_v / outcome_b."""
    keys = ["question_id", "db_id", "difficulty", "question"]
    v = validated.assign(outcome=validated.apply(outcome, axis=1))
    b = baseline.assign(outcome=baseline.apply(outcome, axis=1))
    cols = keys + ["correct", "outcome", "pred_sql", "seconds"]
    paired = v[cols].merge(b[cols], on=keys, suffixes=("_v", "_b"), validate="one_to_one")
    if len(paired) != len(v) or len(paired) != len(b):
        raise ValueError("validated and baseline runs cover different questions")
    return paired


def accuracy_by(paired: pd.DataFrame, by: str, order: list[str] | None = None) -> pd.DataFrame:
    """n and accuracy of both modes per group, plus an 'all' row."""
    t = paired.groupby(by).agg(n=("question_id", "size"), validated=("correct_v", "mean"),
                               baseline=("correct_b", "mean"))
    if order:
        t = t.reindex([o for o in order if o in t.index])
    t.loc["all"] = [len(paired), paired.correct_v.mean(), paired.correct_b.mean()]
    t["n"] = t.n.astype(int)
    return t


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def report(paired: pd.DataFrame, title: str) -> str:
    """Markdown report."""
    t = mcnemar_exact(paired.correct_v, paired.correct_b)
    lines = [f"# {title}", "",
             "Generated by `scripts/compare_bird.py` from `scripts/eval_bird.py` runs (qwen2.5-coder:7b, temperature 0,",
             "BIRD evidence included in the prompt, 30 s per-query timeout). Metric: BIRD execution accuracy",
             "(same set of rows as the gold SQL; row order and duplicates ignored), unchanged. Validated = schema",
             "check + one retry with the error; baseline = one attempt, no schema check (read-only guard kept).", "",
             f"**Validated {_pct(paired.correct_v.mean())} vs baseline {_pct(paired.correct_b.mean())}** "
             f"({int(paired.correct_v.sum())} vs {int(paired.correct_b.sum())} of {len(paired)}). "
             f"Exact McNemar: validated only right {t['only_validated']}, baseline only right {t['only_baseline']}, "
             f"p = {t['p_value']:.4f}.", ""]
    for by, order in (("db_id", None), ("difficulty", DIFFICULTY_ORDER)):
        a = accuracy_by(paired, by, order)
        lines += [f"## Accuracy by {'database' if by == 'db_id' else by}", "",
                  f"| {'database' if by == 'db_id' else by} | n | validated | baseline | difference |", "|---|---|---|---|---|"]
        for grp, r in a.iterrows():
            name = f"**{grp}**" if grp == "all" else grp
            lines.append(f"| {name} | {int(r.n)} | {_pct(r.validated)} | {_pct(r.baseline)} | "
                         f"{100 * (r.validated - r.baseline):+.1f} pts |")
        lines.append("")
    counts = pd.DataFrame({"validated": paired.outcome_v.value_counts(),
                           "baseline": paired.outcome_b.value_counts()}).fillna(0).astype(int)
    lines += ["## Outcomes", "", "| outcome | validated | baseline |", "|---|---|---|"]
    lines += [f"| {o} | {r.validated} | {r.baseline} |" for o, r in counts.iterrows()]
    d = paired[paired.correct_v != paired.correct_b].sort_values("question_id")
    lines += ["", f"## Questions where the modes disagree ({len(d)})", "",
              "| question_id | database | difficulty | right in | baseline outcome | validated outcome |",
              "|---|---|---|---|---|---|"]
    lines += [f"| {r.question_id} | {r.db_id} | {r.difficulty} | {'validated' if r.correct_v else 'baseline'} | "
              f"{r.outcome_b} | {r.outcome_v} |" for r in d.itertuples()]
    return "\n".join(lines) + "\n"


def newest(results_dir: Path, mode: str, tag: str) -> Path:
    paths = sorted(results_dir.glob(f"bird_{mode}_{tag}_*.csv"))
    if not paths:
        raise FileNotFoundError(f"No bird_{mode}_{tag}_*.csv in {results_dir}")
    return paths[-1]


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description="Compare validated vs baseline BIRD runs.")
    parser.add_argument("--runs", nargs=2, type=Path, metavar=("VALIDATED", "BASELINE"))
    parser.add_argument("--tag", default=DEFAULT_TAG)
    parser.add_argument("--results-dir", type=Path, default=RESULTS_DIR)
    parser.add_argument("--out", type=Path, default=REPORT)
    args = parser.parse_args(argv)
    v_path, b_path = args.runs or [newest(args.results_dir, m, args.tag) for m in ("validated", "baseline")]
    print(f"{v_path.name} vs {b_path.name}")
    paired = pair_runs(pd.read_csv(v_path), pd.read_csv(b_path))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report(paired, f"BIRD dev: validated vs baseline ({len(paired)}-question sample)"),
                        encoding="utf-8")
    print(f"Report: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
