"""Shared helpers for data-quality profiling and cleaning (Module 3)."""
import re
import unicodedata
from dataclasses import dataclass, field

import pandas as pd

SNAKE_CASE = re.compile(r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$")
# Misspellings we have seen in source column names, mapped to the correct word.
KNOWN_TYPOS = {"lenght": "length"}
MAX_EXAMPLES = 5


def to_snake_case(name: str) -> str:
    """'Crop_Year' -> 'crop_year', 'Free Meal Count (K-12)' -> 'free_meal_count_k_12'."""
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name.strip())
    name = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower()
    for typo, fix in KNOWN_TYPOS.items():
        name = re.sub(rf"(?<![a-z]){typo}(?![a-z])", fix, name)
    return name or "column"


def column_name_issue(name: str) -> str | None:
    """Return why a column name is odd (not snake_case, spaces, typo), or None if fine."""
    if name != name.strip():
        return "leading/trailing whitespace"
    if any(re.search(rf"(?<![a-z]){t}(?![a-z])", name.lower()) for t in KNOWN_TYPOS):
        return "misspelling"
    if not SNAKE_CASE.match(name):
        return "not snake_case"
    return None


def fold_text(value: str) -> str:
    """Comparison key: strip accents, lowercase, drop punctuation, collapse whitespace."""
    text = unicodedata.normalize("NFKD", str(value)).encode("ascii", "ignore").decode()
    text = re.sub(r"[^0-9a-z]+", " ", text.lower())
    return " ".join(text.split())


def normalize_whitespace(series: pd.Series) -> pd.Series:
    """Trim and collapse internal runs of whitespace in a text column (NaN kept)."""
    return series.str.strip().str.replace(r"\s+", " ", regex=True)


def variant_groups(series: pd.Series, key=fold_text, limit: int = MAX_EXAMPLES) -> list[list[str]]:
    """Groups of distinct raw values that become equal under `key` (spelling variants)."""
    values = pd.Series(series.dropna().astype(str).unique())
    groups = values.groupby(values.map(key)).agg(list)
    multi = [sorted(g) for g in groups if len(g) > 1]
    return sorted(multi, key=len, reverse=True)[:limit]


def _is_text(series: pd.Series) -> bool:
    return pd.api.types.is_object_dtype(series) or pd.api.types.is_string_dtype(series)


def profile_table(df: pd.DataFrame) -> dict:
    """Generic profile: shape, types, missing values, duplicates, name and text issues."""
    columns = []
    for col in df.columns:
        s = df[col]
        info = {
            "name": col,
            "dtype": str(s.dtype),
            "missing": int(s.isna().sum()),
            "missing_pct": round(100 * s.isna().mean(), 2) if len(s) else 0.0,
            "unique": int(s.nunique(dropna=True)),
            "name_issue": column_name_issue(str(col)),
            "untrimmed": 0,
            "variant_groups": [],
            "negative": 0,
        }
        if _is_text(s):
            text = s.dropna().astype(str)
            info["untrimmed"] = int((text != text.str.strip()).sum() + text.str.contains(r"\s{2,}").sum())
            if info["unique"] <= 50_000:  # skip free text / ids with huge cardinality
                info["variant_groups"] = variant_groups(s)
        elif pd.api.types.is_numeric_dtype(s) and not pd.api.types.is_bool_dtype(s):
            info["negative"] = int((s < 0).sum())
        columns.append(info)
    return {
        "rows": len(df),
        "columns": len(df.columns),
        "duplicate_rows": int(df.duplicated().sum()),
        "empty_columns": [c for c in df.columns if df[c].isna().all() and len(df)],
        "constant_columns": [c for c in df.columns if len(df) and df[c].nunique(dropna=False) == 1],
        "column_info": columns,
    }


@dataclass
class Finding:
    """A dataset-specific quality check result."""

    check: str
    count: int
    detail: str = ""


def _md_escape(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def profile_markdown(dataset: str, profiles: dict[str, dict], findings: list[Finding], source: str) -> str:
    """Render a data-quality report for one dataset as markdown."""
    lines = [f"# Data quality: {dataset}", "", f"Source: {source}", "",
             "Generated by `scripts/data_quality.py`. Counts are from the raw files.", ""]
    lines += ["## Summary", "", "| Table | Rows | Columns | Duplicate rows | Columns with missing values | Odd column names |",
              "|---|---|---|---|---|---|"]
    for table, p in profiles.items():
        missing = sum(1 for c in p["column_info"] if c["missing"])
        odd = sum(1 for c in p["column_info"] if c["name_issue"])
        lines.append(f"| {table} | {p['rows']:,} | {p['columns']} | {p['duplicate_rows']:,} | {missing} | {odd} |")
    lines += ["", "## Dataset-specific checks", ""]
    if findings:
        lines += ["| Check | Count | Detail |", "|---|---|---|"]
        lines += [f"| {_md_escape(f.check)} | {f.count:,} | {_md_escape(f.detail)} |" for f in findings]
    else:
        lines.append("No dataset-specific issues found.")
    for table, p in profiles.items():
        lines += ["", f"## Table `{table}`", "",
                  f"{p['rows']:,} rows, {p['columns']} columns, {p['duplicate_rows']:,} exact duplicate rows."]
        if p["empty_columns"]:
            lines.append(f"Empty columns: {', '.join(p['empty_columns'])}.")
        if p["constant_columns"]:
            lines.append(f"Constant columns: {', '.join(p['constant_columns'])}.")
        lines += ["", "| Column | Type | Missing | Unique | Issues |", "|---|---|---|---|---|"]
        for c in p["column_info"]:
            issues = []
            if c["name_issue"]:
                issues.append(f"name: {c['name_issue']}")
            if c["untrimmed"]:
                issues.append(f"{c['untrimmed']:,} values with extra whitespace")
            if c["negative"]:
                issues.append(f"{c['negative']:,} negative values")
            if c["variant_groups"]:
                shown = "; ".join(" / ".join(repr(v) for v in g[:4]) for g in c["variant_groups"][:3])
                issues.append(f"spelling variants: {shown}")
            missing = f"{c['missing']:,} ({c['missing_pct']}%)" if c["missing"] else "0"
            lines.append(f"| {_md_escape(c['name'])} | {c['dtype']} | {missing} | {c['unique']:,} | "
                         f"{_md_escape('; '.join(issues))} |")
    return "\n".join(lines) + "\n"


@dataclass
class CleaningLog:
    """Records each cleaning step and how many rows it affected."""

    entries: list[dict] = field(default_factory=list)

    def record(self, dataset: str, table: str, step: str, rows_affected: int,
               rows_before: int, rows_after: int, note: str = "") -> None:
        """Add one step. `rows_affected` = rows changed or removed by the step."""
        self.entries.append({
            "dataset": dataset, "table": table, "step": step, "rows_affected": int(rows_affected),
            "rows_before": int(rows_before), "rows_after": int(rows_after), "note": note,
        })

    def to_markdown(self) -> str:
        """Render the log grouped by dataset."""
        lines = ["# Cleaning log", "", "Generated by `scripts/prepare_data.py`. One row per cleaning step; "
                 "*rows affected* is the number of rows changed or removed by that step.", ""]
        for dataset in dict.fromkeys(e["dataset"] for e in self.entries):
            lines += [f"## {dataset}", "", "| Table | Step | Rows affected | Rows before | Rows after | Note |",
                      "|---|---|---|---|---|---|"]
            for e in (e for e in self.entries if e["dataset"] == dataset):
                lines.append(f"| {e['table']} | {_md_escape(e['step'])} | {e['rows_affected']:,} | "
                             f"{e['rows_before']:,} | {e['rows_after']:,} | {_md_escape(e['note'])} |")
            lines.append("")
        return "\n".join(lines)


def changed_rows(before: pd.Series, after: pd.Series) -> int:
    """Number of rows where a column's value changed (NaN == NaN counts as unchanged)."""
    return int((~((before == after) | (before.isna() & after.isna()))).sum())


def parse_duration_ms(series: pd.Series) -> pd.Series:
    """'01:23:45.678' / '1:23.4' / '23.456' -> milliseconds (Int64; NaN if unparseable)."""
    def one(text: object) -> float:
        if not isinstance(text, str) or not text.strip():
            return float("nan")
        try:
            seconds = 0.0
            for part in text.strip().split(":"):
                seconds = seconds * 60 + float(part)
        except ValueError:
            return float("nan")
        return round(seconds * 1000)
    return series.map(one).astype("Int64")


def tf_to_bool(series: pd.Series) -> pd.Series:
    """Postgres-style 't'/'f' text -> nullable boolean."""
    return series.map({"t": True, "f": False, True: True, False: False}).astype("boolean")
